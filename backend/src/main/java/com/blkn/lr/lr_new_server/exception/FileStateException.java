package com.blkn.lr.lr_new_server.exception;

public class FileStateException extends FileUploadException {

	private static final long serialVersionUID = 1L;

	public FileStateException() {
		super();
	}

	public FileStateException(String arg0, Throwable arg1, boolean arg2, boolean arg3) {
		super(arg0, arg1, arg2, arg3);
	}

	public FileStateException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public FileStateException(String arg0) {
		super(arg0);
	}

	public FileStateException(Throwable arg0) {
		super(arg0);
	}
	
	
}
